#include "GpuDevReport.h"
#include <cassert>
#include <iostream>

int main(int argc, char **argv)
{
    using namespace gpu_dev;
    assert(ValidOrder({0, 2, 1}, 3));
    assert(!ValidOrder({0, 2, 2}, 3));
    assert(!ValidOrder({0, -1, 2}, 3));
    assert(!ValidOrder({0, 3, 1}, 3));
    assert(!ValidOrder({0}, 0));
    std::vector<int> boundary(52);
    std::iota(boundary.begin(), boundary.end(), 0);
    assert(ValidOrder(boundary, 52));
    boundary.push_back(52);
    assert(!ValidOrder(boundary, 53));
    practice::RouteResult a;
    a.complete = a.pickupOptimized = true;
    a.order = {0, 1}; a.contacts = {1, 2}; a.length = 3;
    auto b = a;
    assert(SameScore(a, b));
    b.length = std::nextafter(a.length, 4.);
    assert(!SameScore(a, b));
    b = a; b.contacts[0] = 2;
    assert(!SameScore(a, b));
    b = a; b.estimated = true;
    assert(!SameScore(a, b));
    b = a; b.complete = false;
    assert(!SameScore(a, b));
    assert(ValidOptions(Preset(0)) && ValidOptions(Preset(1)) && ValidOptions(Preset(2)));
    assert(TotalChecks(Preset(1)) == 98304 && TotalChecks(Preset(2)) == 393216);
    auto invalid = Preset(2); invalid.batch = 2049; assert(!ValidOptions(invalid));
    invalid = Preset(2); invalid.pairs = 13; assert(!ValidOptions(invalid));
    invalid = Preset(2); invalid.seeds = 16385; assert(!ValidOptions(invalid));
    uint64_t ah = 14695981039346656037ull, bh = ah;
    DigestRoute(ah, a); DigestRoute(bh, a); assert(ah == bh);
    b = a; b.contacts[0]++; bh = 14695981039346656037ull;
    DigestRoute(bh, b); assert(ah != bh);
    FrameStats frames;
    for (int i = 0; i < 10000; i++) frames.Observe(i % 100 == 0 ? 40. : 2.);
    assert(frames.count == 10000 && frames.over16 == 100 && frames.over33 == 100);
    assert(frames.P95() >= 2. && frames.P95() <= 2.1 && frames.Quantile(.99) <= 2.1);
    assert(frames.maximum == 40. && frames.Mean() > 2.);
    frames.Observe(NAN); frames.Observe(-1); assert(frames.count == 10000);
    FrameStats slow; slow.Observe(500.); assert(slow.P95() == 500.);
    Observations observed;
    observed.Record(.5, 1000., true, 100., Phase::Cpu, 16);
    observed.Record(.5, 10., true, 100., Phase::Cpu, 16);
    observed.Record(.5, 1000., true, 100., Phase::Gpu, 16);
    observed.Record(.5, 8., true, 100., Phase::Gpu, 16);
    assert(observed.menuFrames == 4 && observed.phases.size() == 2);
    assert(observed.phases[0].intervals.maximum == 10. && observed.phases[1].intervals.maximum == 8.);
    Report bounded;
    for (int i = 0; i < 10000; i++) KeepCase(bounded, false, false);
    for (int i = 0; i < 10000; i++) KeepCase(bounded, true, false);
    assert(bounded.successRows == 64 && bounded.mismatchRows == 16);
    Report r;
    r.phase = Phase::Stopped;
    r.error = "Quoted \"GPU\"\\driver\n\t" + std::string(1, '\x01');
    r.options.key = std::numeric_limits<uint64_t>::max();
    r.observations = observed;
    r.timings.push_back({});
    r.cases.push_back({});
    r.cases.back().cpu = a;
    r.cases.back().gpu.length = std::numeric_limits<double>::infinity();
    auto json = Json(r);
    assert(json.find("\\u0001") != std::string::npos);
    assert(json.find("\"18446744073709551615\"") != std::string::npos);
    assert(json.find("\"length\":null") != std::string::npos);
    assert(json.find("\"gpuKernelMs\":null") != std::string::npos);
    assert(json.find("practice-suite.gpu-dev.v3") != std::string::npos);
    auto folder = argc > 1 ? std::filesystem::path(argv[1]) : std::filesystem::temp_directory_path() / "suite-gpu-report-tests";
    Save(folder / "gpu-report.json", r);
    r.error = "replacement checkpoint";
    Save(folder / "gpu-report.json", r);
    std::ifstream replaced(folder / "gpu-report.json");
    std::string content((std::istreambuf_iterator<char>(replaced)), {});
    assert(content.find("replacement checkpoint") != std::string::npos);
    assert(!std::filesystem::exists(folder / "gpu-report.json.tmp"));
    std::cout << "GPU report: strict scores/digests, stress limits, bounded retention, whole-run/phase histograms, JSON and replacement checkpoints: PASS\n";
}

inline bool ValidCoordinate(float value) {
    return std::isfinite(value) && std::fabs(value) <= 1000000.0f;
}
inline void SanitizeSnapshot(GameData& data) {
    for(auto& v:data.inputGameAxes)if(!ValidCoordinate(v))v=0;
    data.inputState&=2047;data.inputFlags&=0x00ff070f;data.inputMouse&=127;data.inputEventCount=std::clamp(data.inputEventCount,0,8);
    if(!std::isfinite(data.inputSeconds)||data.inputSeconds<0||data.inputSeconds>315360000){data.inputSequence=0;data.inputSeconds=0;}
    for(auto& buttons:data.inputLegacy)buttons&=0xfffff;
    for(auto& buttons:data.inputPadButtons)buttons&=65535;
    for(int i=0;i<24;i++){auto& v=data.inputPadAxes[i];v=std::isfinite(v)?std::clamp(v,i%6<2?0.f:-1.f,1.f):0;}
    data.inputSprint=std::isfinite(data.inputSprint)?std::clamp(data.inputSprint,-1.f,1.f):0;data.inputFlash=std::isfinite(data.inputFlash)?std::clamp(data.inputFlash,-1.f,1.f):0;
    data.replay3dOptions&=0x7F03DBFF;data.replay3dColliderFlags&=15;data.replay3dColliderCount=std::clamp(data.replay3dColliderCount,0,512);
    auto safe=[](float v,float low,float high,float fallback){return std::isfinite(v)?std::clamp(v,low,high):fallback;};
    data.replay3dSpeed=safe(data.replay3dSpeed,.1f,8,1);data.replay3dFollowDistance=safe(data.replay3dFollowDistance,.75f,20,4.3f);data.replay3dFollowHeight=0;data.replay3dTrailSeconds=safe(data.replay3dTrailSeconds,.25f,10,3);
    for(auto* time:{&data.replay3dLoopA,&data.replay3dLoopB})if(!std::isfinite(*time)||*time<0||*time>315360000)*time=0;
    data.replay3dMessage[159]='\0';data.replay3dState=data.replay3dState>=0&&data.replay3dState<=4?data.replay3dState:4;
    if(data.replay3dRunId<0)data.replay3dRunId=0;
    if(!std::isfinite(data.replay3dSeconds)||data.replay3dSeconds<0||data.replay3dSeconds>315360000)data.replay3dSeconds=0;
    if((data.replay3dState==2||data.replay3dState==3)&&data.replay3dRunId==0)data.replay3dState=4;
    data.previousBestSeconds=std::isfinite(data.previousBestSeconds)&&data.previousBestSeconds>0&&data.previousBestSeconds<=315360000?data.previousBestSeconds:0;data.reviewRetained=data.reviewRetained==1;
    data.viewCamera[63]=data.externalTool[95]=data.validationDetail[191]='\0';
    data.runValidity=data.runValidity==1?1:2;data.externalScanStatus=data.externalScanStatus<=3?data.externalScanStatus:3;
    data.gameTargetFps=std::clamp(int(data.gameTargetFps),-1,10000);data.gameVSync=std::clamp(int(data.gameVSync),0,4);
    data.gameRefreshHz=std::isfinite(data.gameRefreshHz)?std::clamp(float(data.gameRefreshHz),0.f,1000.f):0;
    data.cursorLock=std::clamp(int(data.cursorLock),0,2);data.menuInputOwned=data.menuInputOwned==1;
    data.reviewSamples=std::clamp(int(data.reviewSamples),0,32768);
    data.reviewReady=data.reviewReady==1&&data.reviewRunId>0&&data.reviewSamples>0;
    data.wallOutlineCount=std::clamp(int(data.wallOutlineCount),0,200);
    int outlines=0;
    for(int i=0;i<data.wallOutlineCount;i++){
        bool valid=true;for(int j=0;j<8;j++)valid&=ValidCoordinate(data.wallOutlines[i*8+j]);
        if(!valid)continue;
        for(int j=0;j<8;j++)data.wallOutlines[outlines*8+j]=data.wallOutlines[i*8+j];
        data.wallOutlineApproximate[outlines]=data.wallOutlineApproximate[i]==1;outlines++;
    }
    data.wallOutlineCount=outlines;
    data.hitboxDetails[191]='\0';
    data.movementNote[127]='\0';
    data.gameVersion[63]=data.unityVersion[31]=data.gameAssemblyHash[64]=data.reportError[95]=data.statsWarning[95]='\0';
    data.reportEventCount=std::max(0,int(data.reportEventCount));
    data.reportSaveStatus=data.reportSaveStatus<=2?data.reportSaveStatus:2;
    data.runOutcome=data.runOutcome<=5?data.runOutcome:4;
    data.playerReady=data.playerReady==1;
    data.gameFps = std::isfinite(data.gameFps) ? std::clamp(float(data.gameFps),0.f,10000.f) : 0;
    data.seedKind = data.seedKind <= 2 && data.seedKnown ? data.seedKind : 0;
    data.runIntegrity = data.runIntegrity == 1 ? 1 : 0;
    data.timerState = data.timerState<=2 ? data.timerState : 0;
    data.historyCount = std::clamp(int(data.historyCount),0,16);
    for (int* count : {&data.totalRuns,&data.totalFinishedRuns,&data.totalDeaths,&data.totalResets,
        &data.currentRunNumber,&data.sessionAttempts,&data.sessionCompleted,&data.sessionResets,
        &data.attemptsToday,&data.completedToday,&data.resetsToday}) *count = std::max(0,*count);
    data.runProgress = std::isfinite(data.runProgress) ? std::clamp(float(data.runProgress),0.f,1.f) : 0;
    data.furthestProgress = std::isfinite(data.furthestProgress) ? std::clamp(float(data.furthestProgress),0.f,1.f) : 0;
    if (!std::isfinite(data.sessionTimeSeconds) || data.sessionTimeSeconds < 0) data.sessionTimeSeconds = 0;
    if (!std::isfinite(data.averageResetSeconds) || data.averageResetSeconds < 0) data.averageResetSeconds = 0;
    data.statsError[95] = '\0';
    data.modeStatsSinceUtc = data.modeStatsSinceUtc > 0 && data.modeStatsSinceUtc <= 3155378975999999999LL ? data.modeStatsSinceUtc : 0;
    for (int i = 0; i < 24; i++) {
        data.modeAttempts[i] = std::max(0, int(data.modeAttempts[i]));
        data.modeFinished[i] = std::clamp(int(data.modeFinished[i]), 0, int(data.modeAttempts[i]));
        data.modeResets[i] = std::clamp(int(data.modeResets[i]), 0, int(data.modeAttempts[i]));
        data.modeDeaths[i] = std::clamp(int(data.modeDeaths[i]), 0, int(data.modeResets[i]));
        for (double* seconds : {&data.modeFinishSeconds[i], &data.modePlaySeconds[i]}) {
            double value; std::memcpy(&value, seconds, sizeof(value));
            value = std::isfinite(value) && value >= 0 ? std::min(value, 3153600000.) : 0;
            std::memcpy(seconds, &value, sizeof(value));
        }
    }
    for (int i = 0; i < 8; i++) {
        double pb = data.modePersonalBest[i];
        data.modePersonalBest[i] = std::isfinite(pb) && pb > 0 && pb <= 315360000 ? pb : 0;
        data.modePbUtc[i] = data.modePbUtc[i] > 0 && data.modePbUtc[i] <= 3155378975999999999LL ? data.modePbUtc[i] : 0;
    }
    data.totalObjectives = std::clamp(data.totalObjectives, 0, 100000);
    data.objectives = std::clamp(data.objectives, 0, data.totalObjectives);
    data.playerRotY = std::isfinite(data.playerRotY) ? std::fmod(data.playerRotY, 360.f) : 0;
    // Packed float at offset 4310 is unaligned. Pass a value copy to algorithms
    // that otherwise bind references requiring natural float alignment.
    data.smoothedSpeed = std::isfinite(data.smoothedSpeed) ? std::clamp(float(data.smoothedSpeed), 0.f, 1000.f) : 0;
    if (!ValidCoordinate(data.freecamX) || !ValidCoordinate(data.freecamY) || !ValidCoordinate(data.freecamZ)) data.freecamActive = 0;
    data.plannerGenerationMs=std::isfinite(data.plannerGenerationMs)?std::clamp(float(data.plannerGenerationMs),0.f,8.f):0;
    data.timerMonsterCount=std::clamp(int(data.timerMonsterCount),0,128);data.timerMonsterOverflow=std::max(0,int(data.timerMonsterOverflow));
    int actors=0;
    for(int i=0;i<data.timerMonsterCount;i++) {
        float x=data.timerMonsterPositions[i*2],z=data.timerMonsterPositions[i*2+1];
        if(!ValidCoordinate(x)||!ValidCoordinate(z))continue;
        data.timerMonsterPositions[actors*2]=x;data.timerMonsterPositions[actors*2+1]=z;
        data.timerMonsterIds[actors]=data.timerMonsterIds[i];data.timerMonsterStates[actors]=data.timerMonsterStates[i]<=2?data.timerMonsterStates[i]:0;actors++;
    }
    data.timerMonsterCount=actors;
    data.crystalCount = std::clamp(data.crystalCount, 0, 100);
    data.wallCount = std::clamp(data.wallCount, 0, 200);
    data.pathCornerCount = std::clamp(data.pathCornerCount, 0, 20);
    if (!ValidCoordinate(data.playerX) || !ValidCoordinate(data.playerY) || !ValidCoordinate(data.playerZ) || !ValidCoordinate(data.playerRotY)) {
        data.playerX=data.playerY=data.playerZ=data.playerRotY=0;data.playerReady=0;
    }
    if (!ValidCoordinate(data.monsterX) || !ValidCoordinate(data.monsterZ)) data.monsterActive = 0;
    for (int i = 0; i < data.pathCornerCount * 2; i++)
        if (!ValidCoordinate(data.pathCorners[i])) { data.pathCornerCount = 0; break; }
    int crystals = 0;
    for (int i = 0; i < data.crystalCount; i++) {
        float x = data.crystalPositions[i*2], z = data.crystalPositions[i*2+1];
        if (!ValidCoordinate(x) || !ValidCoordinate(z)) continue;
        data.crystalPositions[crystals*2] = x; data.crystalPositions[crystals*2+1] = z; crystals++;
    }
    data.crystalCount = crystals;
    int walls = 0;
    for (int i = 0; i < data.wallCount; i++) {
        float* w = data.wallBoxes + i*4;
        if (!ValidCoordinate(w[0]) || !ValidCoordinate(w[1]) || !ValidCoordinate(w[2]) || !ValidCoordinate(w[3]) ||
            w[2] <= w[0] || w[3] <= w[1]) continue;
        for (int j = 0; j < 4; j++) data.wallBoxes[walls*4+j] = w[j];
        walls++;
    }
    data.wallCount = walls;
    data.mapBoundsValid = data.mapBoundsValid && ValidCoordinate(data.mapMinX) && ValidCoordinate(data.mapMaxX) &&
        ValidCoordinate(data.mapMinZ) && ValidCoordinate(data.mapMaxZ) && data.mapMaxX > data.mapMinX && data.mapMaxZ > data.mapMinZ;
    if (!std::isfinite(data.currentRunTimeSeconds) || data.currentRunTimeSeconds < 0) data.currentRunTimeSeconds = 0;
    if (!std::isfinite(data.personalBestSeconds) || data.personalBestSeconds < 0) data.personalBestSeconds = 0;
    if (!std::isfinite(data.averagePace) || data.averagePace < 0) data.averagePace = 0;
    data.title[63] = data.author[63] = data.version[63] = '\0';
}
